"""Reproduce the bounded 2024 engineering probe; never train or overwrite MT.

Run from the repository: python -m scripts.national_real_pilot
Raw data remain ignored under data/raw/national/engineering-20261027-v1.
The report is local /tmp/national-real-pilot/acquisition.json; publish only after review."""

import hashlib
import json
import sqlite3
import time
import zipfile
from collections import Counter
from pathlib import Path
from uuid import uuid4

import pandas as pd

from src.geo.boundaries import load_boundaries
from src.geo.uf_registry import UF_REGISTRY
from src.national.acquisition import AcquisitionCache, inpe_request, parse_power, power_request
from src.national.dataset import attribute_fire_chunk, normalize_inpe_chunk, normalize_state


def write_immutable_parquet(frame, path):
    """Compare regenerated bytes with existing output; never overwrite a revision."""
    raw = frame.to_parquet(index=False)
    if path.exists():
        if path.read_bytes() != raw:
            raise ValueError(f"Derived output differs; use a new immutable version: {path}")
    else:
        temporary = path.with_name(".staging-" + uuid4().hex)
        temporary.write_bytes(raw)
        temporary.rename(path)
    return hashlib.sha256(raw).hexdigest()


def main():
    root = Path("data/raw/national/engineering-20261027-v1")
    cache = AcquisitionCache(root / "cache", data_version="engineering-20261027-v1", interval=1.5)
    evidence = {
        "data_version": "engineering-20261027-v1",
        "kind": "bounded_engineering_probe_not_national_model",
        "period": ["2024-02-28", "2024-03-03"],
        "power": [],
    }
    for uf, lat, lon in [
        ("51", -12.25, -55.25),
        ("13", -3.25, -60.25),
        ("29", -12.75, -38.25),
        ("35", -23.75, -46.75),
        ("53", -15.75, -47.75),
    ]:
        request = power_request(lat, lon, *evidence["period"])
        path, receipt = cache.fetch(*request)
        payload = json.loads(path.read_bytes())
        frame = parse_power(path.read_bytes(), request[1])
        derived = path.parent / "validated.parquet"
        derived_hash = write_immutable_parquet(frame, derived)
        evidence["power"].append(
            {
                "requested_uf_code": uf,
                "coordinate": [lon, lat],
                "request_key": receipt["request_key"],
                "raw_sha256": receipt["raw_sha256"],
                "raw_bytes": receipt["size_bytes"],
                "acquired_at_utc": receipt["acquired_at_utc"],
                "response_headers": receipt["headers"],
                "derived_sha256": derived_hash,
                "rows": len(frame),
                "header": payload.get("header"),
                "geometry": payload.get("geometry"),
                "parameters": payload.get("parameters"),
                "messages": payload.get("messages"),
                "status": "validated_daily_series",
            }
        )
    path, receipt = cache.fetch(*inpe_request(2024))
    with zipfile.ZipFile(path) as archive:
        members = archive.namelist()
        if len(members) != 1 or not members[0].endswith(".csv") or archive.testzip() is not None:
            raise ValueError("Annual source must contain one valid CSV")
    evidence["inpe"] = {
        "year": 2024,
        "raw_sha256": receipt["raw_sha256"],
        "raw_bytes": receipt["size_bytes"],
        "acquired_at_utc": receipt["acquired_at_utc"],
        "response_headers": receipt["headers"],
        "request_key": receipt["request_key"],
        "members": members,
        "zip_crc_valid": True,
        "sensor_verification": "reference_product_URL_only_no_per_row_satellite_column",
    }
    Path("/tmp/national-real-pilot").mkdir(exist_ok=True)
    Path("/tmp/national-real-pilot/acquisition.json").write_text(json.dumps(evidence, indent=2))
    start = time.monotonic()
    geo = Path("data/geo/national/ibge-2024/BR_UF_2024.geojson.gz")
    receipt = geo.parent / "receipt.json"
    boundaries = load_boundaries(geo, receipt)
    p = Path("/tmp/national-real-pilot/acquisition.json")
    evidence = json.loads(p.read_text())
    for row in evidence["power"]:
        from src.geo.national_grid import assign_point

        assigned = assign_point(row["coordinate"][1], row["coordinate"][0], boundaries)
        row["geographic_assignment"] = assigned
        row["uf_geometry_verified"] = (
            assigned is not None and assigned["uf_code"] == row["requested_uf_code"]
        )
        if not row["uf_geometry_verified"]:
            raise ValueError("Requested pilot coordinate is outside the stated UF")
    rec = evidence["inpe"]
    raw = (
        Path("data/raw/national/engineering-20261027-v1/cache")
        / rec["request_key"]
        / "response.bin"
    )
    lookup = {normalize_state(uf.name): uf.uf_code for uf in UF_REGISTRY}
    counts = Counter()
    chosen = []
    duplicates = 0
    scanned = 0
    origin_counts = Counter()
    invalid_dates = wrong_year = invalid_coordinates = 0
    date_min = date_max = None
    con = sqlite3.connect("/tmp/national-real-pilot/event-index.sqlite")
    con.execute("CREATE TABLE IF NOT EXISTS seen(event_id TEXT PRIMARY KEY)")
    con.execute("DELETE FROM seen")
    with zipfile.ZipFile(raw) as z:
        with z.open(rec["members"][0]) as f:
            for chunk in pd.read_csv(f, encoding="utf-8", chunksize=50000):
                chunk = normalize_inpe_chunk(chunk)
                dates = pd.to_datetime(chunk.data_hora_gmt, errors="coerce", utc=True)
                origin_counts.update(chunk.estado.astype(str))
                invalid_dates += int(dates.isna().sum())
                wrong_year += int(dates.dt.year.ne(2024).sum())
                invalid_coordinates += int(
                    (~chunk.lat.between(-90, 90) | ~chunk.lon.between(-180, 180)).sum()
                )
                date_min = min(date_min or dates.min(), dates.min())
                date_max = max(date_max or dates.max(), dates.max())
                for row, date in zip(chunk.to_dict("records"), dates):
                    scanned += 1
                    identity = json.dumps(
                        [float(row["lat"]), float(row["lon"]), date.isoformat()],
                        separators=(",", ":"),
                    )
                    event_id = hashlib.sha256(identity.encode()).hexdigest()
                    cursor = con.execute(
                        "INSERT OR IGNORE INTO seen(event_id) VALUES (?)", (event_id,)
                    )
                    if cursor.rowcount == 0:
                        duplicates += 1
                        continue
                    code = lookup.get(normalize_state(row["estado"]))
                    if code in ["51", "13", "29", "35", "53"] and counts[code] < 20:
                        chosen.append(row)
                        counts[code] += 1
                con.commit()
    con.close()
    if invalid_dates or wrong_year or invalid_coordinates:
        raise ValueError(
            "Annual source has invalid dates, year or coordinates; inspect before using"
        )
    if any(counts[code] != 20 for code in ["51", "13", "29", "35", "53"]):
        raise ValueError("Missing requested pilot state sample")
    rec.update(
        rows=scanned,
        origin_state_counts=dict(origin_counts),
        date_min=str(date_min),
        date_max=str(date_max),
        csv_encoding="UTF-8 strict",
        issues={
            "invalid_dates": invalid_dates,
            "wrong_year": wrong_year,
            "invalid_coordinates": invalid_coordinates,
        },
        source_completeness="not_established_by_detection_rows",
        cross_chunk_deduplication="disk_backed_sqlite_exact_timestamp_lat_lon",
        status="annual_schema_and_timestamp_scan_not_full_geographic_validation",
    )
    accepted, rejected, audit = attribute_fire_chunk(pd.DataFrame(chosen), boundaries, year=2024)
    out = Path("data/raw/national/engineering-20261027-v1/geographic-sample")
    out.mkdir(exist_ok=True)
    for name, frame in [("accepted", accepted), ("quarantine", rejected)]:
        if not frame.empty:
            write_immutable_parquet(frame, out / (name + ".parquet"))
    evidence["geographic_pilot"] = {
        "scope": "first_20_unique_source_events_per_requested_UF_not_full_annual_attribution",
        "source_uf_sample_counts": dict(counts),
        "selected_rows": len(chosen),
        "assigned_rows": len(accepted),
        "assigned_uf_counts": {str(k): int(v) for k, v in accepted.uf_code.value_counts().items()},
        "quarantine_rows": len(rejected),
        "audit": audit,
        "full_annual_timestamp_coordinate_duplicate_scan": {
            "scanned": scanned,
            "duplicates": duplicates,
            "deduplication": "disk_backed_sqlite_exact_timestamp_lat_lon",
        },
        "geometry_sha256": hashlib.sha256(geo.read_bytes()).hexdigest(),
        "geometry_version": "ibge-2024",
        "elapsed_seconds": round(time.monotonic() - start, 3),
        "source_day_completeness": "not_established",
        "model_training": "not_executed",
        "accepted_sha256": hashlib.sha256((out / "accepted.parquet").read_bytes()).hexdigest(),
    }
    p.write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps(evidence["geographic_pilot"], indent=2))


if __name__ == "__main__":
    main()
